class ScalarTests(unittest.TestCase):
    """标量类型全覆盖（手工向量）。"""

    def test_int_range(self):
        self.assertEqual(msgpack_lite.unpack(b"\x7f"), 127)          # fixint+
        self.assertEqual(msgpack_lite.unpack(b"\xe0"), -32)          # fixint-
        self.assertEqual(msgpack_lite.unpack(b"\xcc\xfa"), 250)
        self.assertEqual(msgpack_lite.unpack(b"\xcd\x01\x00"), 256)
        self.assertEqual(msgpack_lite.unpack(b"\xce\x01\x35\x28\x28"), 20260904)
        self.assertEqual(msgpack_lite.unpack(b"\xcf\x00\x00\x00\x00\x00\x00\x00\x2a"), 42)
        self.assertEqual(msgpack_lite.unpack(b"\xd0\xff"), -1)
        self.assertEqual(msgpack_lite.unpack(b"\xd1\xff\xfe"), -2)
        self.assertEqual(msgpack_lite.unpack(b"\xd2\xff\xff\xff\xff"), -1)
        self.assertEqual(msgpack_lite.unpack(b"\xd3\xff\xff\xff\xff\xff\xff\xff\xfe"), -2)

    def test_float(self):
        self.assertEqual(msgpack_lite.unpack(b"\xca\x40\x20\x00\x00"), 2.5)   # float32
        self.assertAlmostEqual(msgpack_lite.unpack(b"\xcb\x40\x27\xb8\x51\xeb\x85\x1e\xb8"), 11.86)

    def test_str_utf8(self):
        self.assertEqual(msgpack_lite.unpack(b"\xa4\xe6\x97\xa5k"), "日k")     # fixstr
        self.assertEqual(msgpack_lite.unpack(b"\xd9\x03\x61\x62\x63"), "abc")
        self.assertEqual(msgpack_lite.unpack(b"\xda\x00\x03\x61\x62\x63"), "abc")
        self.assertEqual(msgpack_lite.unpack(b"\xdb\x00\x00\x00\x03\x61\x62\x63"), "abc")

    def test_bool_nil(self):
        self.assertIs(msgpack_lite.unpack(b"\xc0"), None)
        self.assertIs(msgpack_lite.unpack(b"\xc2"), False)
        self.assertIs(msgpack_lite.unpack(b"\xc3"), True)

    def test_array_map(self):
        self.assertEqual(msgpack_lite.unpack(b"\x93\x01\x02\x03"), [1, 2, 3])
        self.assertEqual(msgpack_lite.unpack(b"\xdc\x00\x03\x01\x02\x03"), [1, 2, 3])
        self.assertEqual(msgpack_lite.unpack(b"\x81\xa1a\x01"), {"a": 1})
        self.assertEqual(msgpack_lite.unpack(b"\xde\x00\x01\xa1a\x01"), {"a": 1})

    def test_trailing_bytes_rejected(self):
        with self.assertRaises(msgpack_lite.MsgPackError):
            msgpack_lite.unpack(b"\x01\x02")


