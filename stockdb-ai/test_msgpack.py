class FetchIntegrationTests(unittest.TestCase):
    """fetch 层：Content-Type 嗅探 → msgpack 解包转 JSON；文本透传。"""

    def _fake_urlopen(self, body: bytes, content_type: str):
        class _Resp:
            headers = {"Content-Type": content_type}
            def read(self):
                return body
            def __enter__(self):
                return self
            def __exit__(self, *a):
                return False
        return _Resp()

    def test_msgpack_response_converted_to_json_text(self):
        with mock.patch("urllib.request.urlopen",
                        return_value=self._fake_urlopen(
                            bytes.fromhex("81a464617465ce01352828"),
                            "application/x-msgpack")):
            text = free_stockdb.fetch("/?cmd=vals&t=x", timeout=1)
        import json as _json
        rows = _json.loads(text)
        self.assertEqual(rows["date"], 20260904)

    def test_non_msgpack_passthrough(self):
        with mock.patch("urllib.request.urlopen",
                        return_value=self._fake_urlopen('{"ok": 1}'.encode(), "application/json")):
            text = free_stockdb.fetch("/?cmd=get&t=x", timeout=1)
        import json as _json
        self.assertEqual(_json.loads(text)["ok"], 1)


